export type CountryCode = (typeof countryCodes)[number];

const codeSet = new Set<string>(countryCodes);
export function isCountryCode(value: unknown): value is CountryCode {
  return typeof value === 'string' && codeSet.has(value);
}

export type CountryOption = { code: CountryCode; name: string };

/** Country options sorted alphabetically in the given language. */
export function countryOptions(locale: string): CountryOption[] {
  const names = new Intl.DisplayNames([locale], { type: 'region', fallback: 'code' });
  const collator = new Intl.Collator(locale, { sensitivity: 'base' });
  return countryCodes
    .map((code) => ({ code, name: names.of(code) ?? code }))
    .sort((a, b) => collator.compare(a.name, b.name));
}

/** English country name, used as the readable value stored in the contact tool. */
export function englishCountryName(code: CountryCode): string {
  return new Intl.DisplayNames(['en'], { type: 'region', fallback: 'code' }).of(code) ?? code;
}
